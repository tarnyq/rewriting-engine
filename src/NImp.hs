-- Library Functions (Not part of KImp)

eval :: Semantics a -> a -> a
eval rewrites state = eval' rewrites where
    eval' []     = state
    eval' (r:rs) = case (r state) of
                        Nothing     -> eval' rs
                        Just state' -> eval rewrites state'
