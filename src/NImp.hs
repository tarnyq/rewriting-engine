--  Sample programs to test syntax and semantics.
--
--  ./Test  -m KImp -e 'mapM print $ map eval_imp […]'
--      (where … = sum_imp, divide_imp, div0_imp)
--  (Eventually Test will be able find all of the `x :: Pgm` here
--  and evaluate them all for you.)

sum_imp :: Pgm                                      --  'sum.imp'
sum_imp = Pgm ids stmt  where
    ids   = ["n", "sum"]                            --  int n, sum
    stmt = Block
         [ "n" := Int 100                           --  n = 100
         , "sum" := Int 0                           --  sum = 0
         , While (Not (Var "n" :<= (Int 0))) (Block --  while (!(n <= 0)) {
                [ "sum" := (Var "sum" :+ Var "n")   --    sum = sum + n
                , "n" := (Var "n" :+ Negate 1)      --    n = n + -1
                ])                                  --  }
         ]

divide_imp :: Pgm
divide_imp = Pgm ids stmt  where
    ids   = ["a", "b", "r"]                         --  int a, b, r
    stmt = Block
         [ "a" := Int 100                           --  a = 100
         , "b" := Int 3                             --  b = 3
         , "r" := (Var "a" :/ Var "b")              --  r = a / b
         ]

div0_imp :: Pgm
div0_imp = Pgm ids stmt  where
    ids   = ["r"]
    stmt  = Block [ "r" := (Int 42 :/ Int 0) ]

