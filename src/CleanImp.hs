-- User provided Language definition

data State = State { k :: K, store :: Store }  deriving Show
deriving instance Eq State

impInitState :: Pgm -> State
impInitState (Pgm ids pgm) = State [KI_Stmt pgm] (impInitStore ids)

type Store = Map Id Integer
impInitStore :: [Id] -> Store
impInitStore ids = fromList $ zip ids (repeat 0)

type K = [KItem]
data KItem = KI_Stmt Stmt
           | KI_AExp AExp
           | KI_BExp BExp
           deriving Show
deriving instance Eq KItem

imp :: MonadRewrite m State =>  [m ()]
imp = [ assignHeat
      , assignCool
      , assign
      , lookupVar
      , seqStmt
      , emptyBlock
      , while
      , ifHeat
      , ifCool
      , ifT
      , ifF
      , notHeat
      , notCool
      , notBExp
      , leHeatL
      , leCoolL
--    , leHeatR   -- liftK
--    , leCoolR   -- liftK
--    , le        -- liftBExp
--    , addHeatL  -- liftK
--    , addCoolL  -- liftK
--    , addHeatR  -- liftK
--    , addCoolR  -- liftK
--    , add       -- liftAExp
--    , divHeatL  -- liftK
--    , divCoolL  -- liftK
--    , divHeatR  -- liftK
--    , divCoolR  -- liftK
--    , div       -- liftAExp
--    , negate    -- liftAExp
      ]
    where

    assignHeat ::MonadRewrite m State => m ()
    assignHeat = do
        ((KI_Stmt (id := aexp)):rest) <- getK
        guard $ not (isReducedAExp aexp)
        putK $ (KI_AExp aexp):(KI_Stmt (id := AHole)):rest

-- --      assignHeat :: Rewrite K
--         assignHeat ((KI_Stmt (_ := Int _)):_) = Nothing
--         assignHeat ((KI_Stmt (id := aexp)):rest)
--                = Just $ (KI_AExp aexp):(KI_Stmt (id := AHole)):rest
--         assignHeat _ = Nothing
--

    assignCool :: MonadRewrite m State => m ()
    assignCool = do
        ((KI_AExp (Int i)):(KI_Stmt (id := AHole)):rest) <- getK
        putK $ (KI_Stmt (id := (Int i))):rest
-- --      assignCool :: Rewrite K
--         assignCool ((KI_AExp (Int i)):(KI_Stmt (id := AHole)):rest)
--                = Just $ (KI_Stmt (id := (Int i))):rest
--         assignCool _ = Nothing
--
--
    assign :: MonadRewrite m State => m ()
    assign = do
        ((KI_Stmt (id := Int i)):rest) <- getK
        store <- getStore
        put $ State { k = rest, store = insert id i store }
--
--         -- assign :: Rewrite State
--         assign (State ((KI_Stmt (id := Int i)):rest) store)
--              = Just $ State rest (insert id i store)
--         assign _ = Nothing
--
    lookupVar :: MonadRewrite m State => m ()
    lookupVar = do
        ((KI_AExp (Var x)):rest) <- getK
        store <- getStore
        guard $ member x store
        putK $ (KI_AExp $ Int $ findWithDefault undefined x store) : rest

-- --      lookupVar :: Rewrite State
--         lookupVar (State ((KI_AExp (Var x)):rest) store)
--                   | member x store
--                 = Just $ State (exp:rest) store
--                 where exp = KI_AExp $ Int $ findWithDefault undefined x store
--         lookupVar _ = Nothing
--
    seqStmt :: MonadRewrite m State => m ()
    seqStmt = do
        ((KI_Stmt (Block (s:ss))):rest) <- getK
        putK $ (KI_Stmt s):(KI_Stmt $ Block ss):rest
--         -- seqStmt :: Rewrite K
--         seqStmt ((KI_Stmt (Block (s:ss))):rest)
--               = Just $ (KI_Stmt s):(KI_Stmt $ Block ss):rest
--         seqStmt _ = Nothing
    emptyBlock :: MonadRewrite m State => m ()
    emptyBlock = do
        ((KI_Stmt (Block [])):rest) <- getK
        putK rest
--         -- emptyBlock :: Rewrite K
--         emptyBlock ((KI_Stmt (Block [])):rest)
--               = Just $ rest
--         emptyBlock _ = Nothing
--
    while :: MonadRewrite m State => m ()
    while = do
        ((KI_Stmt (While cond body)):rest) <- getK
        putK $ (KI_Stmt $ If cond (Block [body, (While cond body)])
                                  (Block [])
               ) : rest
-- --      while :: Rewrite Stmt
--         while (While cond body)
--             = Just $ (If cond  (Block [body, (While cond body)])
--                                (Block []))
--         while _ = Nothing

    ifHeat :: MonadRewrite m State => m ()
    ifHeat = do
        ((KI_Stmt (If cond stmtTrue stmtFalse)):rest) <- getK
        guard $ not (isReducedBExp cond)
        putK $ (KI_BExp cond) : (KI_Stmt (If BHole stmtTrue stmtFalse)) : rest
-- --      ifHeat :: Rewrite K
--         ifHeat ((KI_Stmt (If (Bool _) _ _)):_) = Nothing
--         ifHeat ((KI_Stmt (If cond stmtTrue stmtFalse)):rest)
--              = Just $ (KI_BExp cond):stmt:rest
--              where stmt = (KI_Stmt (If BHole stmtTrue stmtFalse))
--         ifHeat _ = Nothing

    ifCool :: MonadRewrite m State => m ()
    ifCool = do
        ((KI_BExp (Bool b)):(KI_Stmt (If BHole stmtTrue stmtFalse)):rest) <- getK
        putK $ ((KI_Stmt (If (Bool b) stmtTrue stmtFalse)):rest)
-- --      ifCool :: Rewrite K
--         ifCool ((KI_BExp (Bool b)):(KI_Stmt (If BHole stmtTrue stmtFalse)):rest)
--                = Just $ ((KI_Stmt (If (Bool b) stmtTrue stmtFalse)):rest)
--         ifCool _ = Nothing

    ifT :: MonadRewrite m State => m ()
    ifT = do
        (KI_Stmt (If (Bool True) stmtTrue _)):rest <- getK
        putK $ (KI_Stmt stmtTrue) : rest
-- --      ifT :: Rewrite Stmt
--         ifT (If (Bool True) stmtTrue _) = Just $ stmtTrue
--         ifT _ = Nothing

    ifF :: MonadRewrite m State => m ()
    ifF = do
         (KI_Stmt (If (Bool False) _ stmtFalse)):rest <- getK
         putK $ (KI_Stmt stmtFalse) : rest
-- --      ifF :: Rewrite Stmt
--         ifF (If (Bool False) _ stmtFalse) = Just $ stmtFalse
--         ifF _ = Nothing

    notHeat :: MonadRewrite m State => m ()
    notHeat = do
        (KI_BExp (Not bexp)) : rest <- getK
        guard $ not (isReducedBExp bexp)
        putK $ (KI_BExp bexp) : (KI_BExp (Not BHole)) : rest


-- --      notHeat :: Rewrite K
--         notHeat ((KI_BExp (Not (Bool _))):_) = Nothing
--         notHeat ((KI_BExp (Not bexp)):rest)
--                = Just $ (KI_BExp bexp):(KI_BExp (Not BHole)):rest
--         notHeat _ = Nothing
--
    notCool :: MonadRewrite m State => m ()
    notCool = do
        (KI_BExp (Bool b)):(KI_BExp (Not BHole)):rest <- getK
        putK $ (KI_BExp (Not (Bool b))) : rest

-- --      notCool :: Rewrite K
--         notCool ((KI_BExp (Bool b)):(KI_BExp (Not BHole)):rest)
--                = Just $ ((KI_BExp (Not (Bool b))):rest)
--         notCool _ = Nothing
--
    notBExp :: MonadRewrite m State => m ()
    notBExp = do
        (KI_BExp (Not (Bool b))) : rest <- getK
        putK $ KI_BExp (Bool (not b)) : rest
-- --      notBExp :: Rewrite BExp
--         notBExp (Not (Bool b)) = Just $ (Bool (not b))
--         notBExp _ = Nothing

    leHeatL :: MonadRewrite m State => m ()
    leHeatL = do
        (KI_BExp (lhs :<= rhs)) : rest <- getK
        guard $ not (isReducedAExp lhs)
        putK $ (KI_AExp lhs) : (KI_BExp (AHole :<= rhs)) : rest

-- --      leHeatL :: Rewrite K
--         leHeatL ((KI_BExp (Int _ :<= _)):_) = Nothing
--         leHeatL ((KI_BExp (lhs :<= rhs)):rest)
--               = Just $ (KI_AExp lhs):(KI_BExp (AHole :<= rhs)):rest
--         leHeatL _ = Nothing

    leCoolL :: MonadRewrite m State => m ()
    leCoolL = do
        (KI_AExp (Int i)) : (KI_BExp (AHole :<= rhs)) : rest <- getK
        putK $ (KI_BExp (Int i :<= rhs)):rest

-- --      leCoolL :: Rewrite K
--         leCoolL ((KI_AExp (Int i)):(KI_BExp (AHole :<= rhs)):rest)
--               = Just $ (KI_BExp (Int i :<= rhs)):rest
--         leCoolL _ = Nothing
-- 
-- --      leHeatR :: Rewrite K
--         leHeatR ((KI_BExp (Int _ :<= Int _)):_) = Nothing
--         leHeatR ((KI_BExp (lhs :<= rhs)):rest)
--               = Just $ (KI_AExp rhs):(KI_BExp (lhs :<= AHole)):rest
--         leHeatR _ = Nothing
-- 
-- --      leCoolR :: Rewrite K
--         leCoolR ((KI_AExp (Int i)):(KI_BExp (lhs :<= AHole)):rest)
--               = Just $ (KI_BExp (lhs :<= Int i)):rest
--         leCoolR _ = Nothing
-- 
-- --      le :: Rewrite BExp
--         le (Int i :<= Int j) = Just $ (Bool (i <= j))
--         le _ = Nothing
-- 
-- --      addHeatL :: Rewrite K
--         addHeatL ((KI_AExp (Int _ :+ _)):_) = Nothing
--         addHeatL ((KI_AExp (lhs :+ rhs)):rest)
--                = Just $ (KI_AExp lhs):(KI_AExp (AHole :+ rhs)):rest
--         addHeatL _ = Nothing
-- 
-- --      addCoolL :: Rewrite K
--         addCoolL ((KI_AExp (Int i)):(KI_AExp (AHole :+ rhs)):rest)
--                = Just $ (KI_AExp (Int i :+ rhs)):rest
--         addCoolL _ = Nothing
-- 
-- --      addHeatR :: Rewrite K
--         addHeatR ((KI_AExp (Int _ :+ Int _)):_) = Nothing
--         addHeatR ((KI_AExp (Int lhs :+ rhs)):rest)
--                = Just $ (KI_AExp rhs):(KI_AExp (Int lhs :+ AHole)):rest
--         addHeatR _ = Nothing
-- 
-- --      addCoolR :: Rewrite K
--         addCoolR ((KI_AExp (Int i)):(KI_AExp (Int lhs :+ AHole)):rest)
--                = Just $ (KI_AExp (Int lhs :+ Int i)):rest
--         addCoolR _ = Nothing
-- 
-- --      add :: Rewrite AExp
--         add (Int i :+ Int j) = Just $ (Int (i + j))
--         add _ = Nothing
-- 
-- --      negate :: Rewrite AExp
--         negate (Negate i) = Just $ (Int (-1 * i))
--         negate _ = Nothing
-- 
-- --      divHeatL :: Rewrite K
--         divHeatL ((KI_AExp (Int _ :/ _)):_) = Nothing
--         divHeatL ((KI_AExp (lhs :/ rhs)):rest)
--                = Just $ (KI_AExp lhs):(KI_AExp (AHole :/ rhs)):rest
--         divHeatL _ = Nothing
-- 
-- --      divCoolL :: Rewrite K
--         divCoolL ((KI_AExp (Int i)):(KI_AExp (AHole :/ rhs)):rest)
--                = Just $ (KI_AExp (Int i :/ rhs)):rest
--         divCoolL _ = Nothing
-- 
-- --      divHeatR :: Rewrite K
--         divHeatR ((KI_AExp (Int _ :/ Int _)):_) = Nothing
--         divHeatR ((KI_AExp (Int lhs :/ rhs)):rest)
--                = Just $ (KI_AExp rhs):(KI_AExp (Int lhs :/ AHole)):rest
--         divHeatR _ = Nothing
-- 
-- --      divCoolR :: Rewrite K
